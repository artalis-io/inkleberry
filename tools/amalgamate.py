#!/usr/bin/env python3
"""Generate the embedding distribution from canonical C modules (standard library).
The modular source remains authoritative; CUDA kernels are compiled separately.
SPDX-License-Identifier: Apache-2.0; Copyright (c) 2026 Artalis
"""
import argparse
import difflib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
# Preserve comments, literals, preprocessing numbers and member accesses while
# giving translation-unit-private helpers distinct names in one C translation unit.
TOKEN = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'|'
                   r'(?:0[xX][0-9a-fA-F]+(?:\.[0-9a-fA-F]*)?(?:[pP][+-]?\d+)?|(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)[uUlLfF]*|'
                   r'[A-Za-z_][A-Za-z_0-9]*|->|\s+|.', re.S)
LOCAL = re.compile(r'^\s*#\s*include\s*["<]([^">]+)[">]\s*$', re.M)
BANNER = '/* Generated by tools/amalgamate.py; edit canonical include/ and src/ modules.\n * SPDX-License-Identifier: Apache-2.0; Copyright (c) 2026 Artalis */\n'


def sources(root=ROOT):
    result = {}
    for line in (root / 'config/sources.mk').read_text().splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        match = re.fullmatch(r'([A-Z_]+) = ([A-Za-z0-9_./ -]+)', line)
        if not match or match[1] in result:
            raise ValueError('Unsupported source manifest line: ' + line)
        paths = match[2].split()
        if any(Path(p).is_absolute() or '..' in Path(p).parts for p in paths):
            raise ValueError('Source paths must stay inside the checkout')
        result[match[1]] = paths
    if set(result) != {'HOST', 'GPU_HOST', 'INFER', 'PUBLIC_HEADERS'}:
        raise ValueError('Incomplete source manifest')
    return result


def namespace(text, stem):
    # The source style uses column-zero static definitions. Local statics keep
    # their function scope, so do not need translation-unit namespacing.
    names = set(re.findall(r'^static [^;{=]*?\b(\w+)\s*\(', text, re.M))
    names.update(re.findall(r'^static [^;{=()]*?\b(\w+)\s*(?:\[[^\]]*\])?\s*(?:=|;)', text, re.M))
    for enum in re.findall(r'^enum\s*\{([^}]+)\};', text, re.M):
        names.update(re.findall(r'(?:^|,)\s*(\w+)\s*=', enum))
    mapping = {name: 'sq_am_' + stem + '_' + name for name in names}
    output = []
    previous = ''
    for token in TOKEN.findall(text):
        output.append(mapping.get(token, token) if previous not in ('.', '->') else token)
        if not token.isspace() and not token.startswith(('/*', '//')):
            previous = token
    return ''.join(output)


def generated(root=ROOT):
    groups = sources(root)
    public = {Path(p).name: p for p in groups['PUBLIC_HEADERS']}
    private = {p.name: str(p.relative_to(root)) for p in sorted((root / 'src').glob('*.h'))}
    if len(public) != len(groups['PUBLIC_HEADERS']) or set(public) & set(private):
        raise ValueError('Ambiguous header basename')
    known = {**public, **private}
    seen = set()

    def expand(name):
        if name in seen:
            return ''
        seen.add(name)
        path = root / known[name]
        def include(match):
            return expand(match[1]) if match[1] in known else match[0]
        return '\n/* ' + known[name] + ' */\n' + LOCAL.sub(include, path.read_text()) + '\n'

    header = BANNER + ''.join(expand(Path(p).name) for p in groups['PUBLIC_HEADERS'])
    # Public declarations are provided by the single adjacent header.
    source = BANNER + '#ifndef _POSIX_C_SOURCE\n#define _POSIX_C_SOURCE 200809L\n#endif\n#include "sq.h"\n'
    for name in private:
        source += expand(name)
    for group in ['HOST', 'GPU_HOST', 'INFER']:
        if group == 'GPU_HOST':
            source += '\n#ifdef SQ_ENABLE_CUDA\n'
        for name in groups[group]:
            text = (root / name).read_text()
            text = LOCAL.sub(lambda m: '' if m[1] in known else m[0], text)
            source += '\n/* Module: ' + name + ' */\n' + namespace(text, Path(name).stem) + '\n'
            # Restore preprocessing scope as well as C private-symbol scope.
            macros = re.findall(r'^#define\s+(\w+)', text, re.M)
            source += ''.join('#undef ' + m + '\n' for m in macros if m != '_POSIX_C_SOURCE')
        if group == 'INFER':
            source += '#endif /* SQ_ENABLE_CUDA */\n'
    return {'dist/sq.h': header.rstrip() + '\n', 'dist/sq.c': source.rstrip() + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generated().items():
        path = ROOT / name
        if args.check:
            current = path.read_text() if path.exists() else ''
            if current != text:
                print(''.join(difflib.unified_diff(current.splitlines(True), text.splitlines(True), fromfile=name, tofile='generated')))
                raise SystemExit('Amalgamation is stale; run make amalgamation')
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text)
    print('Embedding distribution verified' if args.check else 'Embedding distribution generated')


if __name__ == '__main__':
    main()
