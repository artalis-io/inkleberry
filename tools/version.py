#!/usr/bin/env python3
"""Generate/check the public version header from the single VERSION authority."""
import argparse
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a = p.parse_args()
v = (ROOT / 'VERSION').read_text().strip()
if not re.fullmatch(r'\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?', v): raise SystemExit('Invalid VERSION')
text = '/* Generated by tools/version.py from VERSION. */\n#ifndef IFN_VERSION_H\n#define IFN_VERSION_H\n#define IFN_VERSION_STRING "'+v+'"\n#define IFN_ABI_VERSION 1u\n#endif\n'
f = ROOT / 'include/ifn_version.h'
if a.check:
    if f.read_text() != text: raise SystemExit('Stale version header: run python3 tools/version.py')
else: f.write_text(text)
